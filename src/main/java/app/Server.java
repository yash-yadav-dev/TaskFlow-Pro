package app;

import com.sun.net.httpserver.*;
import java.io.*;
import java.net.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;

public class Server {
    private static final TaskService service = new TaskService();
    private static final Path WEB = Paths.get("src", "main", "resources", "web");

    public static void main(String[] args) throws IOException {
        HttpServer server = HttpServer.create(new InetSocketAddress(8080), 0);
        server.createContext("/api/tasks", Server::handleTasks);
        server.createContext("/api/import", Server::handleImport);
        server.createContext("/", Server::serveFrontend);
        server.setExecutor(null);
        server.start();
        System.out.println("TaskFlow Pro is live at http://localhost:8080");
        System.out.println("Keep this terminal open while using the app.");
    }

    private static void handleTasks(HttpExchange ex) throws IOException {
        try {
            String method = ex.getRequestMethod();
            if ("GET".equals(method)) {
                List<String> items = new ArrayList<>();
                for (Task t : service.getAll()) items.add(taskJson(t));
                sendJson(ex, 200, "[" + String.join(",", items) + "]");
                return;
            }
            Map<String,String> p = parseForm(new String(ex.getRequestBody().readAllBytes(), StandardCharsets.UTF_8));
            if ("POST".equals(method)) {
                Task t = service.add(p); sendJson(ex, 201, taskJson(t));
            } else if ("PUT".equals(method)) {
                int id = Integer.parseInt(p.getOrDefault("id", "0"));
                boolean ok = service.update(id, p);
                sendJson(ex, ok ? 200 : 404, "{\"success\":" + ok + "}");
            } else if ("DELETE".equals(method)) {
                int id = Integer.parseInt(p.getOrDefault("id", "0"));
                boolean ok = service.delete(id);
                sendJson(ex, ok ? 200 : 404, "{\"success\":" + ok + "}");
            } else sendJson(ex, 405, "{\"error\":\"Method not allowed\"}");
        } catch (IllegalArgumentException e) {
            sendJson(ex, 400, "{\"error\":" + quote(e.getMessage()) + "}");
        } catch (Exception e) {
            sendJson(ex, 500, "{\"error\":" + quote(e.getMessage()) + "}");
        }
    }

    private static void handleImport(HttpExchange ex) throws IOException {
        if (!"POST".equals(ex.getRequestMethod())) { sendJson(ex,405,"{\"error\":\"Method not allowed\"}"); return; }
        try {
            String body = new String(ex.getRequestBody().readAllBytes(), StandardCharsets.UTF_8);
            // Import endpoint accepts URL-encoded rows generated by the frontend.
            Map<String,String> p = parseForm(body);
            int count = 0;
            for (int i=0; p.containsKey("title"+i); i++) {
                Map<String,String> row = new HashMap<>();
                for (String k : List.of("title","description","category","priority","dueDate","status"))
                    row.put(k, p.getOrDefault(k+i, ""));
                service.add(row); count++;
            }
            sendJson(ex,200,"{\"imported\":"+count+"}");
        } catch (Exception e) { sendJson(ex,400,"{\"error\":"+quote(e.getMessage())+"}"); }
    }

    private static void serveFrontend(HttpExchange ex) throws IOException {
        String path = ex.getRequestURI().getPath();
        if (path.equals("/")) path = "/index.html";
        Path target = WEB.resolve(path.substring(1)).normalize();
        if (!target.startsWith(WEB) || !Files.exists(target) || Files.isDirectory(target)) {
            send(ex,404,"Not found"); return;
        }
        String n = target.getFileName().toString();
        String type = n.endsWith(".css") ? "text/css; charset=utf-8" :
            n.endsWith(".js") ? "application/javascript; charset=utf-8" :
            n.endsWith(".svg") ? "image/svg+xml" : "text/html; charset=utf-8";
        ex.getResponseHeaders().set("Content-Type",type);
        ex.getResponseHeaders().set("Cache-Control","no-store");
        byte[] bytes = Files.readAllBytes(target);
        ex.sendResponseHeaders(200,bytes.length);
        try(OutputStream out=ex.getResponseBody()){out.write(bytes);}
    }

    private static Map<String,String> parseForm(String body) {
        Map<String,String> map = new HashMap<>();
        for(String pair:body.split("&")) {
            String[] kv=pair.split("=",2);
            if(kv.length==2) map.put(URLDecoder.decode(kv[0],StandardCharsets.UTF_8),
                URLDecoder.decode(kv[1],StandardCharsets.UTF_8));
        }
        return map;
    }
    private static String taskJson(Task t) {
        return "{\"id\":"+t.getId()+",\"title\":"+quote(t.getTitle())+",\"description\":"+quote(t.getDescription())+
            ",\"category\":"+quote(t.getCategory())+",\"priority\":"+quote(t.getPriority())+
            ",\"dueDate\":"+quote(t.getDueDate())+",\"status\":"+quote(t.getStatus())+
            ",\"createdAt\":"+quote(t.getCreatedAt())+",\"completed\":"+t.isCompleted()+"}";
    }
    private static String quote(String s) {
        if(s==null)return "null";
        return "\""+s.replace("\\","\\\\").replace("\"","\\\"").replace("\n","\\n")
            .replace("\r","\\r").replace("\t","\\t")+"\"";
    }
    private static void sendJson(HttpExchange ex,int status,String body)throws IOException{
        ex.getResponseHeaders().set("Content-Type","application/json; charset=utf-8");send(ex,status,body);
    }
    private static void send(HttpExchange ex,int status,String body)throws IOException{
        byte[] b=body.getBytes(StandardCharsets.UTF_8);ex.sendResponseHeaders(status,b.length);
        try(OutputStream out=ex.getResponseBody()){out.write(b);}
    }
}